def test_telegram_handler_order():
    assert [
        handler.callback.__name__
        for handler in admin_router.message.handlers + admin_router.callback_query.handlers
    ] != []
    for router, expected in ((admin_router, EXPECTED_ADMIN), (user_router, EXPECTED_USER)):
        registered = [
            handler.callback.__name__
            for handler in router.message.handlers + router.callback_query.handlers
        ]
        assert sorted(registered) == sorted(expected)
        assert len(registered) == len(expected)


