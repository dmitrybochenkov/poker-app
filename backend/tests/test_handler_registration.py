def test_telegram_observer_order():
    for router, kind in ((admin_router, "ADMIN"), (user_router, "USER")):
        for observer_name in ("message", "callback_query"):
            observer = getattr(router, observer_name)
            expected = globals()[f"EXPECTED_{kind}_{observer_name.upper()}"]
            assert [handler.callback.__name__ for handler in observer.handlers] == expected
